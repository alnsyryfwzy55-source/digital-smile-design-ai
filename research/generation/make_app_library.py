"""Writes app/src/library.js: several real-tooth sets (one labelled photo each) for the app's simulation.

Same bank as the generation experiment (tooth_bank.py): smile_teeth_v2, Roboflow Universe, CC BY 4.0.
Sets are chosen to cover different proportions (lateral/central width, central width/length), so the app can pick
the set closest to each design. Teeth are stored as PNG with the tooth mask as alpha, at most 128 px tall.
"""
import base64, json, os, sys
import numpy as np, cv2
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import tooth_bank as TB
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
N_SETS = int(sys.argv[1]) if len(sys.argv) > 1 else 8

bank = TB.build_bank(os.path.join(REPO, 'data', 'smile_teeth_v2.zip'))
feat = lambda s: ((s['ratio']['12'] + s['ratio']['22']) / 2, (s['wl']['11'] + s['wl']['21']) / 2)
pool = sorted(bank[:40], key=lambda s: feat(s)[0])
idx = np.linspace(0, len(pool) - 1, N_SETS).round().astype(int)
sets = []
for s in [pool[i] for i in sorted(set(idx))]:
    teeth = {}
    for t in TB.TEETH:
        x = s['teeth'][t]; rgb, a = x['rgb'], x['alpha']
        k = min(1.0, 128 / rgb.shape[0])
        if k < 1:
            rgb = cv2.resize(rgb, None, fx=k, fy=k, interpolation=cv2.INTER_AREA); a = cv2.resize(a, None, fx=k, fy=k, interpolation=cv2.INTER_AREA)
        rgba = np.dstack([rgb, np.clip(a * 255, 0, 255).astype(np.uint8)])
        ok, buf = cv2.imencode('.png', cv2.cvtColor(rgba, cv2.COLOR_RGBA2BGRA), [cv2.IMWRITE_PNG_COMPRESSION, 9])
        teeth[t] = 'data:image/png;base64,' + base64.b64encode(buf.tobytes()).decode()
    sets.append(dict(id=s['id'], lateral_ratio=round(feat(s)[0], 3), central_wl=round(feat(s)[1], 3), teeth=teeth))
lib = dict(source='smile_teeth_v2 (Roboflow Universe datasets, CC BY 4.0; see data/README.md), one labelled photo per set', sets=sets)
hdr = ('/* Real-tooth sets for the simulation (missing teeth, full smile). Source: smile_teeth_v2, built from Roboflow Universe '
       'datasets under CC BY 4.0 (data/README.md lists them). Each tooth: its photo crop with the tooth mask as alpha. '
       'Generated by research/generation/make_app_library.py. */\n')
open(os.path.join(REPO, 'app', 'src', 'library.js'), 'w').write(hdr + 'window.DSDLibrary = ' + json.dumps(lib) + ';\n')
print(len(sets), 'sets', [(s['id'], s['lateral_ratio'], s['central_wl']) for s in sets],
      os.path.getsize(os.path.join(REPO, 'app', 'src', 'library.js')) // 1024, 'KB')
